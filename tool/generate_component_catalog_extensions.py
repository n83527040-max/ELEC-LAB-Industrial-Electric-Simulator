#!/usr/bin/env python3
"""Generate Dart component specs from the shared extension catalogue JSON.

The same JSON is consumed by generate_glb_assets.py, keeping board terminals,
electrical catalog entries and GLB terminal hardware aligned.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tool" / "component_catalog_extensions.json"
TARGET = ROOT / "lib" / "src" / "models" / "component_catalog_extensions.dart"


def quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def number(value: float) -> str:
    value = float(value)
    return str(int(value)) if value.is_integer() else str(value)


def scalar(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return quote(value)
    raise TypeError(f"Unsupported property value: {value!r}")


def main() -> None:
    entries = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by tool/generate_component_catalog_extensions.py.",
        "// Edit tool/component_catalog_extensions.json instead of this file.",
        "import 'dart:ui' show Size;",
        "",
        "import 'component.dart';",
        "import 'geometry.dart';",
        "import 'terminal.dart';",
        "",
        "abstract final class ExtendedComponentCatalog {",
        "  static final Map<ComponentKind, ComponentSpec> byKind =",
        "      <ComponentKind, ComponentSpec>{",
    ]
    for entry in entries:
        lines.extend(
            [
                f"    ComponentKind.{entry['kind']}: ComponentSpec(",
                f"      kind: ComponentKind.{entry['kind']},",
                f"      nameAr: {quote(entry['nameAr'])},",
                f"      nameFr: {quote(entry['nameFr'])},",
                f"      category: ComponentCategory.{entry['category']},",
                f"      size: const Size({number(entry['size'][0])}, {number(entry['size'][1])}),",
                "      terminals: const <TerminalDefinition>[",
            ]
        )
        for terminal in entry["terminals"]:
            lines.extend(
                [
                    "        TerminalDefinition(",
                    f"          id: {quote(terminal['id'])},",
                    f"          label: {quote(terminal['label'])},",
                    f"          position: BoardPoint({number(terminal['x'])}, {number(terminal['y'])}),",
                    f"          kind: TerminalKind.{terminal['kind']},",
                ]
            )
            if terminal.get("phase"):
                lines.append(f"          phase: {quote(terminal['phase'])},")
            lines.extend(["        ),"])
        lines.extend(
            [
                "      ],",
                "      defaultProperties: const <String, Object>{",
            ]
        )
        for key, value in entry["defaults"].items():
            lines.append(f"        {quote(key)}: {scalar(value)},")
        lines.extend(
            [
                "      },",
                f"      description: {quote(entry['description'])},",
            ]
        )
        lines.extend(
            [
                "    ),",
            ]
        )
    lines.extend(["  };", "}", ""])
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {TARGET.relative_to(ROOT)} from {len(entries)} entries")


if __name__ == "__main__":
    main()
